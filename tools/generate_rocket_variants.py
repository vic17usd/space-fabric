#!/usr/bin/env python3
"""Generate nine modular upgrades around the unmodified imported Blockbench fuselage.
One box source drives both native entity geometry and real 3D inventory items.
Run after tools/import_rocket_model.py when reimporting the base model.
"""
from pathlib import Path
import json, copy
from generate_material_resources import png
ROOT=Path(__file__).resolve().parents[1]
RES=ROOT/'src/main/resources'
ASSETS=RES/'assets/space_fabric'
MODULES={}
def box(out,x,y,z,xx,yy,zz): out.append([x,y,z,xx,yy,zz])
def pods(out,y,height,width=.14):
    for side in [-1,1]:
        a,b=sorted([side*.44,side*(.44+width)])
        box(out,a,y,-.2,b,y+height,.2)
def bands(out,y,width=.58):
    # Rectangular collar, with actual open center rather than a box covering the cabin.
    box(out,-width,y,-width,width,y+.09,-.43)
    box(out,-width,y,.43,width,y+.09,width)
    box(out,-width,y,-.43,-.43,y+.09,.43)
    box(out,.43,y,-.43,width,y+.09,.43)
for name in ['mercury','venus','earth','moon','mars','jupiter','saturn','uranus','neptune']:
    out=[];MODULES[name]=out
    if name=='mercury':
        for y in [.85,1.10,1.35,1.60]: pods(out,y,.05,.30)
        bands(out,2.40,.49)
    elif name=='venus':
        for y in [.50,1.10,2.20]: bands(out,y,.57)
        pods(out,.65,1.40,.22)
    elif name=='earth':
        pods(out,.55,.55,.13)
        box(out,-.04,2.95,-.04,.04,3.45,.04)
        box(out,-.27,3.27,-.035,.27,3.32,.035)
    elif name=='moon':
        pods(out,.8,.8,.20)
        for x in [-.72,.50]:
            for z in [-.68,.46]:box(out,x,.02,z,x+.22,.14,z+.22)
    elif name=='mars':
        pods(out,.55,.95,.25)
        for y in [.65,.85,1.05,1.25]:box(out,-.32,y,-.62,.32,y+.06,-.44)
    elif name=='jupiter':
        for y in [.35,.75,1.35,2.25]:bands(out,y,.64)
        for x in [-.64,.56]:
            for z in [-.64,.56]:box(out,x,.35,z,x+.08,2.34,z+.08)
    elif name=='saturn':
        bands(out,.8,.76);bands(out,1.85,.66)
        pods(out,.9,.7,.10)
    elif name=='uranus':
        pods(out,.50,1.65,.18)
        box(out,-.33,.5,-.61,.33,1.9,-.44)
        bands(out,2.05,.54)
    else:
        for y in [.45,1.0,1.7,2.25]:bands(out,y,.60)
        pods(out,.5,1.8,.22)
        box(out,-.32,.6,-.64,.32,1.8,-.44)
# Render with direct vertices, independent of Sodium ModelPart UV caching.
java='''package dev.vic17usd.spacefabric.client.rocket;

import com.mojang.blaze3d.vertex.PoseStack.Pose;
import com.mojang.blaze3d.vertex.VertexConsumer;
import dev.vic17usd.spacefabric.space.RocketVariant;
import org.joml.Vector3f;

/** Generated by tools/generate_rocket_variants.py. Exterior equipment in metres, Y up. */
public final class RocketModules {
    private RocketModules() { }
    public static float[][] boxes(RocketVariant variant) {
        return switch(variant) {
'''
for name,boxes in MODULES.items():
    java+=f'            case {name.upper()} -> new float[][] {{\n'
    for b in boxes: java+='                {'+','.join(f'{n:.4f}F' for n in b)+'},\n'
    java+='            };\n'
java+='''            default -> new float[0][];
        };
    }
    public static void renderGeometry(RocketVariant variant,Pose pose,VertexConsumer output,int light,int overlay) {
        for(var b:boxes(variant)) {
            float x=b[0],y=b[1],z=b[2],xx=b[3],yy=b[4],zz=b[5];
            float[][][] faces={
                {{x,y,z},{x,y,zz},{x,yy,zz},{x,yy,z}},
                {{xx,y,zz},{xx,y,z},{xx,yy,z},{xx,yy,zz}},
                {{x,yy,zz},{xx,yy,zz},{xx,yy,z},{x,yy,z}},
                {{x,y,z},{xx,y,z},{xx,y,zz},{x,y,zz}},
                {{xx,y,z},{x,y,z},{x,yy,z},{xx,yy,z}},
                {{x,y,zz},{xx,y,zz},{xx,yy,zz},{x,yy,zz}}
            };
            for(var face:faces) {
                var a=new Vector3f(face[0]);
                var normal=new Vector3f(face[1]).sub(a).cross(new Vector3f(face[2]).sub(a)).normalize();
                pose.transformNormal(normal,normal);
                for(int i=0;i<4;i++) {
                    var point=new Vector3f(face[i]);pose.pose().transformPosition(point);
                    float u=(i==0||i==3?16:36)/512F,v=(i<2?48:72)/512F;
                    output.addVertex(point.x,point.y,point.z,variant.color,u,v,overlay,light,normal.x,normal.y,normal.z);
                }
            }
        }
    }
}
'''
(ROOT/'src/main/java/dev/vic17usd/spacefabric/client/rocket/RocketModules.java').write_text(java)
COLORS=[(197,204,210),(217,173,53),(68,142,224),(214,219,225),(230,107,60),(183,110,58),(226,196,120),(98,215,214),(66,105,206)]
NAMES_ES=['Mercurio','Venus','la Tierra','la Luna','Marte','Júpiter','Saturno','Urano','Neptuno']
MATERIALS=['minecraft:quartz','minecraft:obsidian','minecraft:copper_ingot','minecraft:glass','minecraft:iron_ingot','minecraft:netherite_scrap','minecraft:gold_ingot','minecraft:blue_ice','minecraft:prismarine_crystals']
base=json.loads((ASSETS/'models/item/rocket.json').read_text())
langs={lang:json.loads((ASSETS/f'lang/{lang}.json').read_text()) for lang in ['es_es','en_us']}
for (name,boxes),color,es,material in zip(MODULES.items(),COLORS,NAMES_ES,MATERIALS):
    # 26.1 rejects item models whose quads use different atlases. Keep both the
    # imported fuselage and the new accent sprite under item/, never block/.
    accent=f'rocket_module_{name}'
    pixels=[[tuple(max(0,min(255,c+((x*3+y*5)%7)-3)) for c in color)+(255,) for x in range(16)] for y in range(16)]
    png(f'assets/space_fabric/textures/item/{accent}.png',pixels)
    model=copy.deepcopy(base);model['textures']['accent']=f'space_fabric:item/{accent}'
    for x,y,z,xx,yy,zz in boxes:
        scale=16/3.284210526
        model['elements'].append({'from':[round(8-xx*scale,5),round(y*scale,5),round(8-zz*scale,5)],'to':[round(8-x*scale,5),round(yy*scale,5),round(8-z*scale,5)],'faces':{face:{'uv':[0,0,16,16],'texture':'#accent'} for face in ['up','down','north','south','east','west']}})
    # Keep using the original texture atlas, not nonexistent variant PNGs.
    model['textures']['0']='space_fabric:item/rocket'
    for suffix in ['rocket','rocket_kit']:
        path=f'{name}_{suffix}'
        (ASSETS/f'items/{path}.json').write_text(json.dumps({'model':{'type':'minecraft:model','model':f'space_fabric:item/{path}'}},indent=2)+'\n')
    (ASSETS/f'models/item/{name}_rocket.json').write_text(json.dumps(model,indent=2)+'\n')
    (ASSETS/f'models/item/{name}_rocket_kit.json').write_text(json.dumps({'parent':'minecraft:item/generated','textures':{'layer0':f'space_fabric:item/{name}_rocket_kit'}},indent=2)+'\n')
    recipe={'type':'minecraft:crafting_shaped','category':'misc','pattern':['IPI','RCR','IPI'],'key':{'I':'minecraft:iron_ingot','P':material,'R':'minecraft:redstone','C':'minecraft:copper_block'},'result':{'id':f'space_fabric:{name}_rocket_kit','count':1}}
    (RES/f'data/space_fabric/recipe/{name}_rocket_kit.json').write_text(json.dumps(recipe,indent=2)+'\n')
    for lang,data in langs.items():
        data[f'item.space_fabric.{name}_rocket']=f'Cohete de {es}' if lang=='es_es' else f'{name.title()} Rocket'
        data[f'item.space_fabric.{name}_rocket_kit']=f'Kit del cohete de {es}' if lang=='es_es' else f'{name.title()} Rocket Upgrade Kit'
        data[f'rocket.space_fabric.variant.{name}']=es.removeprefix('la ').capitalize() if lang=='es_es' else name.title()
for lang,data in langs.items():
    data.update({'item.space_fabric.rocket_rating':'Casco: %s bar; %s a %s °C' if lang=='es_es' else 'Hull: %s bar; %s to %s °C','gui.space_fabric.route_safe':'Destino compatible con este cohete.' if lang=='es_es' else 'Destination compatible with this rocket.','gui.space_fabric.route_unsafe':'La protección del cohete no permite este destino.' if lang=='es_es' else 'Rocket protection does not permit this destination.','rocket.space_fabric.variant.base':'Básico' if lang=='es_es' else 'Basic','gui.space_fabric.hull':'Casco: %s%%' if lang=='es_es' else 'Hull: %s%%','message.space_fabric.upgrade_empty':'Baja del cohete para instalar el kit.' if lang=='es_es' else 'Leave the rocket before installing the kit.','message.space_fabric.rocket_unsuitable':'El casco o la protección no permiten este viaje.' if lang=='es_es' else 'Hull or environmental protection does not permit this trip.','item.space_fabric.rocket_kit_help':'Clic derecho sobre un cohete vacío para instalar.' if lang=='es_es' else 'Right-click an unoccupied rocket to install.'})
    (ASSETS/f'lang/{lang}.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
print('Generated nine rocket meshes, items, upgrades, recipes and translations.')

