   private final KeyframeAnimation locomotionAnimation = AshplumeEmberwalkerAnimations.LOCOMOTION.bake(this.root());
   private final KeyframeAnimation[] actionAnimations = new KeyframeAnimation[AshplumeEmberwalkerAnimations.ACTIONS.length];
