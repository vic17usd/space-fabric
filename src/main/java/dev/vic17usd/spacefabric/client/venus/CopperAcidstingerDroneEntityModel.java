   @Override public void setupAnim(CopperAcidstingerDroneRenderState state) {
      super.setupAnim(state);long millis=(long)(state.ageInTicks*50);
      if(state.actionIndex>=0&&state.actionIndex<actionAnimations.length) {
         actionIdleAnimations[state.actionIndex].apply(millis,1);
         actionAnimations[state.actionIndex].apply(state.actionTimeMillis,1);
      } else if(state.horizontalTravelSpeed>.02F)locomotionAnimation.applyWalk(state.horizontalTravelPosition,state.horizontalTravelSpeed,LOCOMOTION_TIME_SCALE,2.5F);
      else idleAnimation.apply(millis,1);
   }

