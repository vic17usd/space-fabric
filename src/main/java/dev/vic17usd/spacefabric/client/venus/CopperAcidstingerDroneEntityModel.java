   private static Polygon quad(
      Direction direction, float u1, float v1, float u2, float v2, Vertex first, Vertex second, Vertex third, Vertex fourth
   ) {
      return new Polygon(new Vertex[]{first, second, third, fourth}, u1, v1, u2, v2, 512.0F, 512.0F, false, direction);
   }

   @Environment(EnvType.CLIENT)
   private static final class RigCuboid extends Cube {
      private RigCuboid(float x, float y, float z, float width, float height, float depth) {
         super(0, 0, x, y, z, width, height, depth, 0.0F, 0.0F, 0.0F, false, 512.0F, 512.0F, EnumSet.allOf(Direction.class));
      }

      public void compile(Pose entry, VertexConsumer vertices, int light, int overlay, int color) {
         Vector3f transformed = new Vector3f();

         for (Polygon face : this.polygons) {
            entry.transformNormal(face.normal(), transformed);
            float normalX = transformed.x();
            float normalY = transformed.y();
            float normalZ = transformed.z();

            for (Vertex vertex : face.vertices()) {
               entry.pose()
                  .transformPosition(vertex.worldX(), vertex.worldY(), vertex.worldZ(), transformed);
               vertices.addVertex(
                  transformed.x(), transformed.y(), transformed.z(), color, vertex.u(), vertex.v(), overlay, light, normalX, normalY, normalZ
               );
            }
         }
      }
   }
